// Writes src/styles/themes/<id>.css for the styles defined in code in src/expo/styles/*.ts.
// The TypeScript files are the source of truth for these twelve styles (Expo reads them directly); the CSS is
// generated so the web packages paint the same colors and materials. Run after editing any of them:
//   node scripts/sync-expo-styles.mjs      (then `npm run build:tokens` / `npm run build`)
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const outDir = path.join(root, "src/styles/themes");

// `terminal.ts` reads `Platform.select`; the web value is the `default` branch.
const reactNativeStub = {
  name: "react-native-stub",
  setup(b) {
    b.onResolve({ filter: /^react-native$/ }, () => ({ path: "react-native", namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({ contents: "exports.Platform = { select: (o) => o.default ?? o.web };", loader: "js" }));
  },
};
const result = await build({ entryPoints: [path.join(root, "src/expo/styles/index.ts")], bundle: true, platform: "node", format: "cjs", write: false, plugins: [reactNativeStub], logLevel: "silent" });
const mod = { exports: {} };
new Function("module", "exports", "require", result.outputFiles[0].text)(mod, mod.exports, () => ({}));
const styles = mod.exports.nativeStyles;

const decl = (name, value) => (value === undefined || value === "" ? "" : `  --bokoui-${name}: ${value};\n`);
const backdrop = (e) => (e.blur || e.saturate ? [e.blur ? `blur(${e.blur}px)` : "", e.saturate ? `saturate(${e.saturate}%)` : ""].filter(Boolean).join(" ") : undefined);

/** Material tokens of one effects object; see `surface-*` in src/styles/tokens.css. */
function effectDecls(fx = {}) {
  let out = "";
  const { card, control, pressed, field, solid, page } = fx;
  if (card) {
    out += decl("card-bg", card.background) + decl("card-image", card.gradient) + decl("card-shadow", card.shadow) + decl("card-border", card.borderColor) + decl("card-backdrop", backdrop(card));
    if (card.borderWidth !== undefined) out += decl("card-border-width", `${card.borderWidth}px`);
  }
  if (control) {
    const bg = control.background ?? "var(--bokoui-surface)";
    out += decl("control-bg", bg) + decl("control-image", control.gradient) + decl("control-shadow", control.shadow) + decl("control-border", control.borderColor) + decl("control-backdrop", backdrop(control));
  }
  if (pressed) out += decl("pressed-bg", pressed.background ?? "var(--bokoui-muted)") + decl("pressed-image", pressed.gradient) + decl("pressed-shadow", pressed.shadow);
  if (field) out += decl("field-bg", field.background ?? "var(--bokoui-field)") + decl("field-image", field.gradient) + decl("field-shadow", field.shadow) + decl("field-border-effect", field.borderColor);
  if (solid) out += decl("solid-image", solid.gradient) + decl("solid-shadow", solid.shadow) + decl("solid-border", solid.borderColor);
  if (page) out += decl("page-image", page.gradient) + decl("page-bg", "transparent");
  if (fx.fontFamily) out += decl("font", fx.fontFamily) + decl("font-heading", fx.fontFamily);
  return out;
}

const tokenDecls = (map = {}) => Object.entries(map).map(([k, v]) => decl(k, v)).join("");

/** Declarations as an ordered map; the same name later in the list replaces the earlier one. */
const flatTokens = new Set(fs.readFileSync(path.join(outDir, "flat.css"), "utf8").match(/--bokoui-[\w-]+/g));
const toMap = (text) => new Map([...text.matchAll(/^  (--bokoui-[\w-]+): (.*);$/gm)].map((m) => [m[1], m[2]]));
const render = (map) => [...map].map(([k, v]) => `  ${k}: ${v};\n`).join("");

for (const [id, theme] of Object.entries(styles)) {
  const selector = `:root[data-theme="${id}"]`;
  const base = toMap(tokenDecls(theme.tokens) + effectDecls(theme.effects));
  const light = toMap(tokenDecls(theme.light) + effectDecls(theme.lightEffects));
  const dark = toMap(tokenDecls(theme.dark) + effectDecls(theme.darkEffects));
  // A material value that is the same in both modes is written once, in the style's own block. Tokens that flat.css
  // also defines per mode stay per mode: the token builders let flat's mode block win over a theme's base block.
  for (const [k, v] of light) {
    if (dark.get(k) === v && !flatTokens.has(k)) {
      base.set(k, v);
      light.delete(k);
      dark.delete(k);
    }
  }
  const css =
    `/* ${theme.label}. GENERATED by scripts/sync-expo-styles.mjs from src/expo/styles; edit the TypeScript file and run the script. */\n` +
    `${selector} {\n${render(base)}}\n\n` +
    `${selector}:not([data-mode="dark"]) {\n${render(light)}}\n\n` +
    `${selector}[data-mode="dark"] {\n${render(dark)}}\n`;
  fs.writeFileSync(path.join(outDir, `${id}.css`), css);
}

fs.writeFileSync(
  path.join(outDir, "materials.css"),
  "/* The twelve material styles. GENERATED by scripts/sync-expo-styles.mjs. */\n" + Object.keys(styles).map((id) => `@import "./${id}.css";\n`).join(""),
);
console.log(`wrote ${Object.keys(styles).length} theme files`);
