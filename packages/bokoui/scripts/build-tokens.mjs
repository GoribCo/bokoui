// Resolves every style x mode from src/styles/themes/*.css into plain JSON-able token maps.
// Writes src/expo/tokens.generated.ts (used by bokoui/expo); with --dist also dist/tokens.json (bokoui/tokens.json).
// CSS stays the single source of truth; run again after editing any theme file.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "src/styles/themes");

const parse = (css, match) => {
  css = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const out = {};
  for (const m of css.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    if (!match(m[1].trim())) continue;
    for (const d of m[2].matchAll(/--bokoui-([\w-]+):\s*([^;]+);/g)) out[d[1]] = d[2].trim();
  }
  return out;
};

const flat = fs.readFileSync(path.join(dir, "flat.css"), "utf8");
const LIGHT = ':root:not([data-mode="dark"])';
const DARK = ':root[data-mode="dark"]';

const tokens = {};
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".css") && f !== "index.css")) {
  const id = file.replace(".css", "");
  const css = fs.readFileSync(path.join(dir, file), "utf8");
  const style = {
    ...parse(flat, (s) => s === ":root"),
    ...parse(css, (s) => s === `:root[data-theme="${id}"]`),
  };
  tokens[id] = {};
  for (const [mode, base, suffix] of [
    ["light", LIGHT, ':not([data-mode="dark"])'],
    ["dark", DARK, '[data-mode="dark"]'],
  ]) {
    tokens[id][mode] = {
      ...style,
      ...parse(flat, (s) => s === base),
      ...parse(css, (s) => s === `:root[data-theme="${id}"]${suffix}`),
    };
  }
}

const generated = `// GENERATED by scripts/build-tokens.mjs from src/styles/themes/*.css. Do not edit.
export const generatedTokens: Record<string, Record<"light" | "dark", Record<string, string>>> = ${JSON.stringify(tokens, null, 2)};
`;
fs.mkdirSync(path.join(root, "src/expo"), { recursive: true });
fs.writeFileSync(path.join(root, "src/expo/tokens.generated.ts"), generated);
if (process.argv.includes("--dist")) {
  fs.mkdirSync(path.join(root, "dist"), { recursive: true });
  fs.writeFileSync(path.join(root, "dist/tokens.json"), JSON.stringify(tokens, null, 2));
}
console.log(`wrote tokens for ${Object.keys(tokens).length} styles${process.argv.includes("--dist") ? " (+ dist/tokens.json)" : ""}`);
